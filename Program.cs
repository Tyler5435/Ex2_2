namespace Ex2_2
{
    internal class Program
    {
        static void Main(string[] args)
        {
            Console.ForegroundColor = ConsoleColor.Red; // Set the console text color to red
            Console.WriteLine("This is the first color of the rainbow."); // Display the first color of the rainbow
            Console.ReadKey(); // Wait for the user to press a key

            Console.WriteLine(""); // Display an empty line

            Console.ForegroundColor = ConsoleColor.DarkYellow; // Set the console text color to dark yellow
            Console.WriteLine("This is the second color of the rainbow."); // Display the second color of the rainbow
            Console.ReadKey(); // Wait for the user to press a key

            Console.WriteLine(""); // Display an empty line

            Console.ForegroundColor = ConsoleColor.Yellow; // Set the console text color to yellow
            Console.WriteLine("This is the third color of the rainbow."); // Display the third color of the rainbow
            Console.ReadKey(); // Wait for the user to press a key

            Console.WriteLine(""); // Display an empty line

            Console.ForegroundColor = ConsoleColor.Green; // Set the console text color to green
            Console.WriteLine("This is the fourth color of the rainbow."); // Display the fourth color of the rainbow
            Console.ReadKey(); // Wait for the user to press a key

            Console.WriteLine(""); // Display an empty line

            Console.ForegroundColor = ConsoleColor.Blue; // Set the console text color to blue
            Console.WriteLine("This is the fifth color of the rainbow."); // Display the fifth color of the rainbow
            Console.ReadKey(); // Wait for the user to press a key

            Console.WriteLine(""); // Display an empty line

            Console.ForegroundColor = ConsoleColor.DarkMagenta; // Set the console text color to dark magenta
            Console.WriteLine("This is the sixth color of the rainbow."); // Display the sixth color of the rainbow
            Console.ReadKey(); // Wait for the user to press a key

            Console.WriteLine(""); // Display an empty line

            Console.ForegroundColor = ConsoleColor.Magenta; // Set the console text color to magenta
            Console.WriteLine("This is the seventh color of the rainbow."); // Display the seventh color of the rainbow
            Console.ReadKey(); // Wait for the user to press a key

            Console.WriteLine(""); // Display an empty line

            Console.ResetColor(); // Reset the console text color to the default color
            Console.ReadKey(); // Wait for the user to press a key before closing the console window
        }
    }
}
